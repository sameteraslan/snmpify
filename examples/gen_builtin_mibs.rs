//! Generates src/mib/builtin.rs: the standard MIB modules as a table of
//! facts (names, OIDs, kinds, types, access, enumerations, display
//! hints, indexes, units), without descriptions or other module text.
//!
//!     python3 tools/mibs/fetch.py /tmp/mibs --netsnmp-container snmpify-snmpd
//!     cargo run --example gen_builtin_mibs -- /tmp/mibs > src/mib/builtin.rs

use std::fmt::Write;

use snmpify::mib::Mib;

fn q(s: &str) -> String {
    format!("{s:?}")
}

fn opt(s: &Option<String>) -> String {
    match s {
        Some(s) => format!("Some({})", q(s)),
        None => "None".into(),
    }
}

fn main() {
    let dir = std::env::args().nth(1).expect("a directory of MIB modules");
    let mut mib = Mib::new();
    let report = mib.load_dir(&dir).expect("readable directory");
    let (modules, failed) = (report.loaded, report.failed);
    for (f, e) in &failed {
        eprintln!("FAILED {f}: {e}");
    }
    let unresolved = mib.unresolved();
    if !failed.is_empty() || !unresolved.is_empty() {
        eprintln!("unresolved: {unresolved:?}");
        std::process::exit(1);
    }
    let mut modules: Vec<String> = modules;
    modules.sort();
    modules.dedup();
    let idx = |m: &str| modules.iter().position(|x| x == m).expect("known module");

    let mut objects: Vec<_> = mib.objects().filter(|o| !o.module.is_empty()).collect();
    // Where modules overlap, the SMIv2 names win (RFC1213-MIB → SNMPv2-MIB,
    // IF-MIB, IP-MIB …): SMIv1 modules go last for each OID.
    let smiv1 = |m: &str| m == "RFC1213-MIB" || m == "RFC1155-SMI";
    objects.sort_by(|a, b| {
        a.oid
            .cmp(&b.oid)
            .then(smiv1(&a.module).cmp(&smiv1(&b.module)))
            .then(a.module.cmp(&b.module))
    });
    let mut types: Vec<_> = mib.textual_conventions().collect();
    types.sort_by(|a, b| (&a.module, &a.name).cmp(&(&b.module, &b.name)));

    let mut s = String::new();
    writeln!(
        s,
        "//! Generated by `cargo run --example gen_builtin_mibs` from the modules"
    )
    .unwrap();
    writeln!(
        s,
        "//! fetched by tools/mibs/fetch.py (RFCs, IANA registries, net-snmp). Facts only:"
    )
    .unwrap();
    writeln!(
        s,
        "//! names, OIDs, kinds, types, access, enumerations, display hints. Do not edit."
    )
    .unwrap();
    writeln!(s, "#![allow(clippy::all)]\n").unwrap();
    writeln!(s, "use super::*;\n").unwrap();
    writeln!(s, "/// The modules [`Mib::standard`] knows.").unwrap();
    writeln!(s, "pub const STANDARD_MODULES: &[&str] = &[").unwrap();
    for m in &modules {
        writeln!(s, "    {},", q(m)).unwrap();
    }
    writeln!(s, "];\n").unwrap();
    writeln!(s, "struct B {{ m: u8, n: &'static str, o: &'static [u32], k: Kind, t: Option<&'static str>, b: Option<BaseType>, a: Option<Access>, s: Option<Status>, e: &'static [(i64, &'static str)], h: Option<&'static str>, i: &'static [&'static str], u: Option<&'static str> }}\n").unwrap();
    writeln!(s, "struct T {{ m: u8, n: &'static str, t: &'static str, e: &'static [(i64, &'static str)], h: Option<&'static str> }}\n").unwrap();
    writeln!(s, "static OBJECTS: &[B] = &[").unwrap();
    for o in &objects {
        let enums: Vec<String> = o
            .enums
            .iter()
            .map(|(n, l)| format!("({n}, {})", q(l)))
            .collect();
        let index: Vec<String> = o.index.iter().map(|i| q(i)).collect();
        writeln!(
            s,
            "    B {{ m: {}, n: {}, o: &{:?}, k: Kind::{:?}, t: {}, b: {}, a: {}, s: {}, e: &[{}], h: {}, i: &[{}], u: {} }},",
            idx(&o.module),
            q(&o.name),
            o.oid.as_slice(),
            o.kind,
            opt(&o.type_name),
            o.base.map_or("None".into(), |b| format!("Some(BaseType::{b:?})")),
            o.access.map_or("None".into(), |a| format!("Some(Access::{a:?})")),
            o.status.map_or("None".into(), |a| format!("Some(Status::{a:?})")),
            enums.join(", "),
            opt(&o.display_hint),
            index.join(", "),
            opt(&o.units),
        )
        .unwrap();
    }
    writeln!(s, "];\n").unwrap();
    writeln!(s, "static TYPES: &[T] = &[").unwrap();
    for t in &types {
        let enums: Vec<String> = t
            .enums
            .iter()
            .map(|(n, l)| format!("({n}, {})", q(l)))
            .collect();
        writeln!(
            s,
            "    T {{ m: {}, n: {}, t: {}, e: &[{}], h: {} }},",
            idx(&t.module),
            q(&t.name),
            q(&t.type_name),
            enums.join(", "),
            opt(&t.display_hint)
        )
        .unwrap();
    }
    writeln!(s, "];\n").unwrap();
    s.push_str(
        r#"pub(crate) fn install(m: &mut Mib) {
    for t in TYPES {
        m.add_type(TextualConvention {
            module: STANDARD_MODULES[t.m as usize].to_string(),
            name: t.n.to_string(),
            type_name: t.t.to_string(),
            enums: t.e.iter().map(|(n, l)| (*n, l.to_string())).collect(),
            display_hint: t.h.map(str::to_string),
        });
    }
    for b in OBJECTS {
        m.add_builtin(MibObject {
            module: STANDARD_MODULES[b.m as usize].to_string(),
            name: b.n.to_string(),
            oid: Oid::from_slice(b.o),
            kind: b.k,
            type_name: b.t.map(str::to_string),
            base: b.b,
            enums: b.e.iter().map(|(n, l)| (*n, l.to_string())).collect(),
            display_hint: b.h.map(str::to_string),
            access: b.a,
            status: b.s,
            index: b.i.iter().map(|s| s.to_string()).collect(),
            units: b.u.map(str::to_string),
        });
    }
}
"#,
    );
    print!("{s}");
    eprintln!(
        "{} modules, {} objects, {} types",
        modules.len(),
        objects.len(),
        types.len()
    );
}
